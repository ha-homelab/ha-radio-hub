#!/usr/bin/env python3
"""Generate LP-I0 native KiCad source from design.py. Run with KiCad's Python.
The routed PCB is kept separately: regeneration produces integrated-unrouted.kicad_pcb.
"""
import argparse, csv, json, shutil, uuid
from pathlib import Path
import pcbnew as pcb
from design import ROOT, parts, connectors, SOURCES
p=argparse.ArgumentParser();p.add_argument('--libraries',type=Path,required=True);args=p.parse_args()
LIB=args.libraries
BUILD=ROOT/'.build';BUILD.mkdir(exist_ok=True)
LOCAL=ROOT/'footprints'/'Hub.pretty';LOCAL.mkdir(exist_ok=True)
U=lambda s:str(uuid.uuid5(uuid.NAMESPACE_URL,'https://ha-homelab/LP-I0/'+s))
Q=lambda s:json.dumps(str(s))

def simple_fp(name,pads,rect,descr,th=False):
    x1,y1,x2,y2=rect
    lines=[f'(footprint {Q(name)} (version 20260206) (generator "pcbnew") (layer "F.Cu") (descr {Q(descr)})',
    f'(property "Reference" "REF**" (at 0 {y1-1.5} 0) (layer "F.SilkS") (effects (font (size 1 1) (thickness 0.15))))',
    f'(property "Value" {Q(name)} (at 0 {y2+1.5} 0) (layer "F.Fab") (effects (font (size 1 1) (thickness 0.15))))',
    f'(attr {"through_hole" if th else "smd"})']
    for layer,d in [('F.Fab',0),('F.CrtYd',0.5)]:
        lines.append(f'(fp_rect (start {x1-d} {y1-d}) (end {x2+d} {y2+d}) (stroke (width 0.05) (type solid)) (fill none) (layer "{layer}"))')
    for n,x,y,w,h in pads:
        lines.append(f'(pad "{n}" {"thru_hole" if th else "smd"} {"rect" if n==1 or not th else "oval"} (at {x} {y}) (size {w} {h}) '+('(drill 1.1) (layers "*.Cu" "*.Mask")' if th else '(layers "F.Cu" "F.Paste" "F.Mask")')+')')
    lines.append(')');(LOCAL/(name+'.kicad_mod')).write_text('\n'.join(lines)+'\n')

# Dimensions are independently transcribed from manufacturer drawings.
# Custom footprints generated by footprints.py; module pads and board headers are distinct.
from footprints import build_custom
build_custom(LOCAL)
# Vendor only footprints actually used. Preserve source metadata and remove external3D references.
for obj in parts:
    fp=obj['footprint']
    if not fp or fp.startswith('Hub:'):continue
    lib,name=fp.split(':');src=LIB/'footprints'/(lib+'.pretty')/(name+'.kicad_mod')
    if not src.exists():raise FileNotFoundError(src)
    txt=src.read_text()
    # 3D paths are optional; no phantom local dependency in this portable package.
    at=txt.find('\n\t(model ')
    if at>=0:txt=txt[:at]+'\n)\n'
    (LOCAL/(name+'.kicad_mod')).write_text(txt)
(ROOT/'fp-lib-table').write_text('(fp_lib_table (version 7) (lib (name "Hub")(type "KiCad")(uri "${KIPRJMOD}/footprints/Hub.pretty")(options "")(descr "Portable LP-I0 footprints")))\n')
for obj in parts:
    if obj['footprint']:obj['footprint']='Hub:'+obj['footprint'].split(':')[1]

# Symbol bodies contain actual physical pin numbers; net labels are on real wire stubs.
symbols=[];instances=[];wires=[];labels=[];ncs=[]
rootid=U('schematic')
def geom(obj):
    logical_pins={k:v for k,v in obj['pins'].items() if k not in obj.get('mechanical_pads',[])}
    count=len(logical_pins);left=(count+1)//2 if count>8 else count
    r=[]
    for i,(num,net) in enumerate(logical_pins.items()):
        right=i>=left;rank=i-left if right else i
        r.append((num,net,20.32 if right else -20.32, -rank*2.54,180 if right else 0,right))
    return r,left
for idx,obj in enumerate(parts):
    ref=obj['ref'];g,left=geom(obj);name='LP_'+ref.replace('#','')
    ymin=-max(1,left-1)*2.54-2.54
    sym=[f'(symbol {Q(name)} (pin_names (offset 0.508)) (in_bom {"no" if ref.startswith("#") else "yes"}) (on_board {"no" if ref.startswith("#") else "yes"})',
    f'(property "Reference" {Q(ref)} (at 0 5.08 0) (effects (font (size 1.27 1.27))))',f'(property "Value" {Q(obj["model"])} (at 0 2.54 0) (effects (font (size 1.27 1.27))))',
    f'(symbol "{name}_0_1" (rectangle (start -15.24 1.27) (end 15.24 {ymin}) (stroke (width 0.254) (type default)) (fill (type background))))',f'(symbol "{name}_1_1"']
    for num,net,x,y,ang,right in g:
        typ=obj['types'].get(num,'passive');pinname=net or 'NC'
        sym.append(f'(pin {typ} line (at {x} {y} {ang}) (length 5.08) (name {Q(pinname)} (effects (font (size 0.8 0.8)))) (number {Q(num)} (effects (font (size 1 1)))))')
    sym.append('))');symbols.append('\n'.join(sym))
    x=50.8+(idx%8)*99.06;y=25.4+(idx//8)*76.2
    iid=U('symbol/'+ref)
    inst=[f'(symbol (lib_id "Hub:{name}") (at {x:.4f} {y:.4f} 0) (unit 1) (in_bom {"no" if ref.startswith("#") else "yes"}) (on_board {"no" if ref.startswith("#") else "yes"}) (dnp no) (uuid "{iid}")',f'(property "Reference" {Q(ref)} (at {x} {y-6.35} 0) (effects (font (size 1.27 1.27))))',f'(property "Value" {Q(obj["model"])} (at {x} {y-3.81} 0) (effects (font (size 1.0 1.0))))',f'(property "Footprint" {Q(obj["footprint"])} (at {x} {y} 0) (effects (font (size 1 1)) hide))']
    for num,net,px,py,ang,right in g:
        inst.append(f'(pin {Q(num)} (uuid "{U(ref+"/pin/"+num)}"))')
        xx=round(x+px,4);yy=round(y-py,4);end=round(xx+(5.08 if right else -5.08),4)
        if net is None:ncs.append(f'(no_connect (at {xx} {yy}) (uuid "{U(ref+"/NC/"+num)}"))')
        else:
            wires.append(f'(wire (pts (xy {xx} {yy}) (xy {end} {yy})) (stroke (width 0) (type default)) (uuid "{U(ref+"/wire/"+num)}"))')
            labels.append(f'(global_label {Q(net)} (shape input) (at {end} {yy} {0 if right else 180}) (effects (font (size 0.9 0.9)) (justify left bottom)) (uuid "{U(ref+"/label/"+num)}"))')
    inst.append(f'(instances (project "integrated" (path "/{rootid}" (reference {Q(ref)}) (unit 1)))) )');instances.append('\n'.join(inst))
(ROOT/'Hub.kicad_sym').write_text('(kicad_symbol_lib (version 20250114) (generator "kicad_symbol_editor")\n'+'\n'.join(symbols)+'\n)\n')
(ROOT/'sym-lib-table').write_text('(sym_lib_table (version 7) (lib (name "Hub")(type "KiCad")(uri "${KIPRJMOD}/Hub.kicad_sym")(options "")(descr "LP-I0 explicit physical pin symbols")))\n')
embedded=[s.replace('(symbol "LP_', '(symbol "Hub:LP_',1) for s in symbols]
sch=f'(kicad_sch (version 20250114) (generator "eeschema") (uuid "{rootid}") (paper "User" 850 1170) (title_block (title "LP-I0 integrated radio hub - ENGINEERING PROTOTYPE") (date "2026-10-17") (rev "I0") (comment 1 "3.3V logic; isolated PoE; manufacturer module pads; not approved for production"))\n(lib_symbols\n'+'\n'.join(embedded)+')\n'+'\n'.join(wires+labels+ncs+instances)+'\n)\n'
(ROOT/'integrated.kicad_sch').write_text(sch)

# Board geometry and connectivity. Autorouter output becomes integrated.kicad_pcb only after verification.
board=pcb.BOARD();board.SetCopperLayerCount(4)
settings=board.GetDesignSettings();settings.m_CopperEdgeClearance=pcb.FromMM(0.25);settings.m_TrackMinWidth=pcb.FromMM(0.15);settings.m_MinClearance=pcb.FromMM(0.15);settings.m_ViasMinSize=pcb.FromMM(0.7);settings.m_MinThroughDrill=pcb.FromMM(0.2)
netsettings=settings.m_NetSettings
default=netsettings.GetDefaultNetclass();default.SetViaDiameter(pcb.FromMM(0.8));default.SetViaDrill(pcb.FromMM(0.4))
for cname, width, clearance, patterns in [('Power',0.8,0.2,['3v3','3v3_analog','5v_fused','5v_pd']),('PoE',0.5,0.5,['POE_*'])]:
    nc=pcb.NETCLASS(cname);nc.SetViaDiameter(pcb.FromMM(0.8));nc.SetViaDrill(pcb.FromMM(0.4));nc.SetTrackWidth(pcb.FromMM(width));nc.SetClearance(pcb.FromMM(clearance));netsettings.SetNetclass(cname,nc)
    for pattern in patterns:netsettings.SetNetclassPatternAssignment(pattern,cname)
nets={}
for obj in parts:
    for n in obj['pins'].values():
        if n is not None and n not in nets:
            ni=pcb.NETINFO_ITEM(board,n);board.Add(ni);nets[n]=ni
for obj in parts:
    if not obj['footprint']:continue
    fp=pcb.FootprintLoad(str(LOCAL),obj['footprint'].split(':')[1]);fp.SetReference(obj['ref']);fp.SetValue(obj['model']);fp.SetFPID(pcb.LIB_ID('Hub',obj['footprint'].split(':')[1]));fp.SetPosition(pcb.VECTOR2I(pcb.FromMM(obj['xy'][0]),pcb.FromMM(obj['xy'][1])));fp.SetOrientationDegrees(obj['rotation']);fp.SetPath(pcb.KIID_PATH('/'+rootid+'/'+U('symbol/'+obj['ref'])))
    actual_pads={pad.GetNumber() for pad in fp.Pads() if pad.GetNumber()}
    assert actual_pads == set(obj['pins']), (obj['ref'],'unplanned physical pad',actual_pads-set(obj['pins']))
    assert {n for n,v in obj['pins'].items() if v is not None} <= actual_pads, (obj['ref'],'wired symbol pin missing from footprint')
    for pad in fp.Pads():
        net=obj['pins'].get(pad.GetNumber())
        if net:pad.SetNet(nets[net])
    fp.Reference().SetTextSize(pcb.VECTOR2I(pcb.FromMM(0.9),pcb.FromMM(0.9)));fp.Reference().SetTextThickness(pcb.FromMM(0.15));fp.Value().SetVisible(False)
    if obj["ref"]=="U3":fp.Reference().SetPosition(pcb.VECTOR2I(pcb.FromMM(139),pcb.FromMM(16.5)))
    if obj["ref"]=="J3":fp.Reference().SetPosition(pcb.VECTOR2I(pcb.FromMM(153),pcb.FromMM(43)))
    if obj["ref"].startswith(("R","C","FB","Y")):fp.Reference().SetLayer(pcb.F_Fab)
    board.Add(fp)
# Deterministic PHY routes are protected before routing other buses.
from preroute import add_phy_routes
add_phy_routes(board)
for a,b in [((0,0),(160,0)),((160,0),(160,142)),((160,142),(0,142)),((0,142),(0,0))]:
    s=pcb.PCB_SHAPE();s.SetShape(pcb.SHAPE_T_SEGMENT);s.SetStart(pcb.VECTOR2I(pcb.FromMM(a[0]),pcb.FromMM(a[1])));s.SetEnd(pcb.VECTOR2I(pcb.FromMM(b[0]),pcb.FromMM(b[1])));s.SetLayer(pcb.Edge_Cuts);s.SetWidth(pcb.FromMM(0.05));board.Add(s)
hole_name='MountingHole_3.2mm_M3'
shutil.copyfile(LIB/'footprints'/'MountingHole.pretty'/(hole_name+'.kicad_mod'),LOCAL/(hole_name+'.kicad_mod'))
for i,(x,y) in enumerate([(5,5),(155,23),(5,137),(155,137)],1):
    fp=pcb.FootprintLoad(str(LOCAL),hole_name);fp.SetFPID(pcb.LIB_ID('Hub',hole_name));fp.SetReference('H'+str(i));fp.SetValue('M3 NPTH');fp.SetBoardOnly(True);fp.SetPosition(pcb.VECTOR2I(pcb.FromMM(x),pcb.FromMM(y)));fp.Reference().SetVisible(False);fp.Value().SetVisible(False);board.Add(fp)
for txt,x,y,size in [('LP-I0 INTEGRATED / PROTOTYPE',65,4,1.2),('PoE PRIMARY',28,135,1.0),('3V3 LOGIC / NO HOT PLUG',80,139,1.0),('USB DATA ONLY',18,44,0.9)]:
    t=pcb.PCB_TEXT(board);t.SetText(txt);t.SetPosition(pcb.VECTOR2I(pcb.FromMM(x),pcb.FromMM(y)));t.SetTextSize(pcb.VECTOR2I(pcb.FromMM(size),pcb.FromMM(size)));t.SetTextThickness(pcb.FromMM(0.15));t.SetLayer(pcb.F_SilkS);board.Add(t)
# Keep-out regions prevent the autorouter from crossing antenna and isolation areas.
def keepout(rect, name):
    z=pcb.ZONE(board);z.SetIsRuleArea(True);z.SetLayerSet(pcb.LSET.AllCuMask());z.SetDoNotAllowPads(False);z.SetDoNotAllowTracks(True);z.SetDoNotAllowVias(True);z.SetDoNotAllowZoneFills(True)
    z.SetZoneName(name);poly=z.Outline();poly.NewOutline()
    x1,y1,x2,y2=rect
    for x,y in [(x1,y1),(x2,y1),(x2,y2),(x1,y2)]:poly.Append(int(pcb.FromMM(x)),int(pcb.FromMM(y)))
    board.Add(z)
keepout((26,0,58,12),'S3 antenna clearance - all layers')
keepout((80,0,104,17),'H2 antenna clearance - all layers')
keepout((141.05,0,149.85,4.8),'MGM240P built-in antenna - all layers')
# Ag97000 Figure14: >5.5mm width, >7.46 above and >3 below pin row.
keepout((66,119,72,141),'PoE primary-secondary isolation')
# RJ45 body projects left of locating posts; no copper under magnetics.
# Its primary and signal pins project inward and remain available for routing.
keepout((0,94,17,106),'No copper below RJ45 transformer body')

# Dedicated internal ground reference. The router may use F.Cu, In2.Cu and B.Cu;
# In1.Cu is reserved for this plane. Keepouts also apply to plane fills.
z=pcb.ZONE(board);z.SetLayer(pcb.In1_Cu);z.SetNet(nets['gnd']);z.SetZoneName('Dedicated secondary ground reference')
z.SetLocalClearance(pcb.FromMM(0.25));z.SetMinThickness(pcb.FromMM(0.20));z.SetPadConnection(pcb.ZONE_CONNECTION_FULL);z.SetIslandRemovalMode(0)
poly=z.Outline();poly.NewOutline()
# The left lower area carries primary PoE: never place a secondary plane under it.
for x,y in [(1,1),(159,1),(159,141),(73,141),(73,117),(1,117)]:poly.Append(pcb.FromMM(x),pcb.FromMM(y))
board.Add(z)
from preroute import add_stitching
add_stitching(board)
(ROOT/'integrated.kicad_pro').write_text(json.dumps({'meta':{'filename':'integrated.kicad_pro','version':1}})+'\n')
board.BuildListOfNets();board.SynchronizeNetsAndNetClasses(False);board.BuildConnectivity();pcb.SaveBoard(str(BUILD/'integrated-unrouted.kicad_pcb'),board)
pcb.ExportSpecctraDSN(board,str(BUILD/'integrated.dsn'))
# ExportSpecctraDSN saves project settings with the board basename.
shutil.copyfile(BUILD/'integrated-unrouted.kicad_pro',ROOT/'integrated.kicad_pro')
# Specctra class-class clearance gives the autorouter the same domain separation as KiCad.
dsn=(BUILD/'integrated.dsn').read_text()
dsn=dsn.replace(str(BUILD/'integrated.dsn'),'integrated.dsn')
dsn=dsn.replace('(layer In1.Cu\n      (type signal)', '(layer In1.Cu\n      (type power)')
dsn=dsn.replace('  (wiring\n', '  (wiring\n')
pos=dsn.index('  (wiring\n')
pre=dsn[:pos];insert=pre.rfind('  )')
pre=pre[:insert]+'    (class_class (classes PoE kicad_default) (rule (clearance 2500)))\n    (class_class (classes PoE Power) (rule (clearance 2500)))\n'+pre[insert:]
(BUILD/'integrated.dsn').write_text(pre+dsn[pos:])
connector_rows=[]
fp_by_ref={f.GetReference():f for f in board.GetFootprints()}
for obj in parts:
    if not obj['ref'].startswith('J'):continue
    f=fp_by_ref[obj['ref']]
    base=next((c for c in connectors if c['ref']==obj['ref']),{})
    destinations={
      'J3':{'1':'CC1101 module VCC 3.3V','2':'CC1101 GND','3':'CC1101 SCLK','4':'CC1101 SI/MOSI','5':'CC1101 SO/MISO','6':'CC1101 CSn','7':'CC1101 GDO0 TX open-drain from S3 GPIO4','8':'CC1101 GDO2 RX to S3 GPIO5'},
      'J4':{'1':'ZAC93 pin1 3.3V; verify actual revision','2':'ZAC93 pin6 GND','3':'ZAC93 pin8 RX from SC16 TXA','4':'ZAC93 pin10 TX to SC16 RXA','5':'ZAC93 pin9 GND'},
      'J5':{'1':'LD2450 +5V','2':'LD2450 GND','3':'LD2450 TX to S3 GPIO40','4':'LD2450 RX from S3 GPIO39'},
      'J6':{'1':'BME680 QT GND','2':'BME680 QT 3.3V','3':'BME680 SDA to S3 GPIO1','4':'BME680 SCL to S3 GPIO2'},
      'J7':{'1':'Target voltage reference 3.3V; programmer must not source power','2':'Programmer GND','3':'MGM240P PA01/SWCLK modulepad8','4':'MGM240P PA02/SWDIO modulepad9','5':'MGM240P RESET modulepad31; pull low only','6':'MGM240P PA00 boot modulepad7; pull low only'},
      'J8':{'1':'Target voltage reference3.3V; programmer must not source power','2':'Programmer GND','3':'H2 TX GPIO24/modulepad31 to programmer RX','4':'H2 RX GPIO23/modulepad30 from programmer TX; hold S3 reset','5':'H2 EN/modulepad8; pull low only','6':'H2 BOOT GPIO9/modulepad23; pull low only'}}
    members=[]
    for n,net in obj['pins'].items():
        voltage=0 if net=='gnd' else 5 if net in ['5v_fused','usb_vbus'] else None if net is None or net.startswith(('POE','eth_','mag_','usb_d')) or net in ['chassis','usb_cc1','usb_cc2','mg24_reset'] else 3.3
        destination='Mechanical hold-down, not a signal' if n=='MP' else destinations.get(obj['ref'],{}).get(n, ('RJ45 magjack PCB solder terminal '+n+' / '+str(net)) if obj['ref']=='J1' else ('USB-C receptacle contact '+n+' / '+str(net)))
        members.append(dict(number=n,net=net,destination=destination,voltage_v=voltage,notes='PCB top/component view. Signal voltage is not specified for differential/analog or primary PoE nets.'))
    connector_rows.append(dict(ref=obj['ref'],model=obj['model'],mating_model={'J1':'Shielded Cat5e/Cat6 8P8C cable','J2':'USB-C data cable','J6':'SHR-04V-S; prefer Adafruit 4210 precrimped QT cable'}.get(obj['ref'],base.get('mating_model','Use manufacturer specified mating cable')),label=base.get('label',obj['notes']),viewing_convention=('Magjack PCB solder-terminal numbers; these are NOT external RJ45 8P8C contact numbers.' if obj['ref']=='J1' else 'PCB top view; mating cable contact face is mirrored. Square pad or silk identifies pin1 where numbered.'),contacts=base.get('contacts','USB-C cable' if obj['ref']=='J2' else 'SSH-003T-P0.2-H' if obj['ref']=='J6' else 'Manufacturer specified'),pins=members,board_position_mm=list(obj['xy']),rotation_deg=obj['rotation'],pad_centers_mm=[dict(number=p.GetNumber(),x=pcb.ToMM(p.GetPosition().x),y=pcb.ToMM(p.GetPosition().y)) for p in f.Pads() if p.GetNumber()]))
(ROOT/'connectors.json').write_text(json.dumps(dict(schema_version=1,revision='LP-I0',status='engineering_prototype_not_fabrication_release',sources=SOURCES,connectors=connector_rows),indent=2)+'\n')
(ROOT/'netlist.json').write_text(json.dumps(dict(revision='LP-I0',parts=parts),indent=2)+'\n')
with (ROOT/'assembly-bom.csv').open('w',newline='') as f:
    w=csv.writer(f);w.writerow(['Reference','Quantity','Manufacturer part / value','Footprint','Note','Source'])
    for obj in parts:
        if not obj['ref'].startswith('#'):w.writerow([obj['ref'],1,obj['model'],obj['footprint'],obj['notes'],SOURCES.get(obj['source'],'')])
print(f'Generated {len(parts)} symbols, {len(nets)} nets and {len(connectors)} keyed harness connectors')
