"""One explicit, reproducible RF-switch contract for each XIAO antenna path."""

MODES = ("onboard", "external")


def configuration(mode):
    if mode not in MODES:
        raise ValueError("Unknown XIAO antenna mode: " + str(mode))
    return {
        "mode": mode,
        "rf_path": "RF2/U.FL" if mode == "external" else "RF1/onboard ceramic",
        "select_gpio": "PB04", "select_level": int(mode == "external"),
        "enable_gpio": "PB05", "enable_level": 1,
    }


def header(mode):
    level = configuration(mode)["select_level"]
    return ("/* Generated by the MC1 recipe; do not change after generation. */\n"
            "#ifndef MC1_ANTENNA_CONFIG_H\n#define MC1_ANTENNA_CONFIG_H\n"
            f"#define MC1_ANTENNA_EXTERNAL {level}\n#endif\n")


def artifact_prefix(mode):
    configuration(mode)
    return "mc1-xiao-mg24-" + mode
