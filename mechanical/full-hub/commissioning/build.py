#!/usr/bin/env python3
"""Build the editable ZAC93 first-fit project and verify its standalone slice."""
import argparse
import math
from pathlib import Path
import os
import re
import subprocess
import tempfile
import zipfile

HERE = Path(__file__).resolve().parent
PROFILE = HERE / 'xy3-zac93-pla.ini'
STEM = 'FH1-ZAC93-XY3-PLA'


def embed_settings(raw, expanded, output):
    # PrusaSlicer 2.9.6 CLI exports its own 3MF geometry without print settings.
    # Supply the same configuration member used by the PrusaSlicer GUI.
    with zipfile.ZipFile(raw) as src:
        members = {name: src.read(name) for name in src.namelist()}
    settings = [line for line in expanded.read_text().splitlines() if line and not line.startswith('#')]
    members['Metadata/Slic3r_PE.config'] = ''.join('; ' + line + '\n' for line in settings).encode()
    model = '3D/3dmodel.model'
    members[model] = re.sub(rb'^ <metadata name="(?:CreationDate|ModificationDate)">[^<]+</metadata>\n',
                            b'', members[model], flags=re.MULTILINE)
    with zipfile.ZipFile(output, 'w') as dest:
        for name, data in sorted(members.items()):
            if re.search(rb'/Users/|/home/|/private/tmp/|/var/folders/|(?<![A-Za-z])[A-Za-z]:[\\/]|\\\\[\w.-]+\\', data):
                raise ValueError(f'Unexpected local path in {name}')
            info = zipfile.ZipInfo(name)
            info.compress_type = zipfile.ZIP_DEFLATED
            info.external_attr = 0o100644 << 16
            dest.writestr(info, data)


def commands(path):
    lines = path.read_text().splitlines()
    if not lines or not lines[0].startswith('; generated by PrusaSlicer 2.9.6 on '):
        raise ValueError('Unexpected slicer version in exported G-code')
    return [cmd for line in lines if (cmd := line.partition(';')[0].strip())]


def validate_start(lines):
    cold = ['G21', 'G90', 'M82', 'M107', 'M104 S0', 'M140 S0', 'G28', 'G1 Z8 F300']
    if lines[:len(cold)] != cold or len(lines) == len(cold):
        raise ValueError('Unexpected cold startup')
    positioning = re.fullmatch(r'G1 X(\d+(?:\.\d+)?) Y(\d+(?:\.\d+)?) F1800', lines[len(cold)])
    if not positioning:
        raise ValueError('Expected raised XY approach to the skirt entry')
    x, y = positioning.groups()
    # With this pinned slicer/profile, every command until the skirt is known.
    # No moves may slip between the completed high approach and first extrusion.
    transition = [
        'M400', 'M104 S200', 'M109 S200', 'G92 E0', 'G21', 'G90', 'M82', 'G92 E0',
        'M107', 'G1 E-2 F2400', 'G92 E0', 'G1 Z.35 F180', f'G1 X{x} Y{y} F6000',
        'G1 Z.35 F180', 'G1 E2 F2400', 'G1 F900',
    ]
    start = len(cold) + 1
    first = start + len(transition)
    if lines[start:first] != transition or len(lines) <= first:
        raise ValueError('Unexpected move or mode before the skirt. Review the raised approach.')
    deposit = re.fullmatch(r'G1 X([\d.]+) Y([\d.]+) E([\d.]+)', lines[first])
    if not deposit:
        raise ValueError('Expected first XY extrusion at the skirt')
    nx, ny, e = map(float, deposit.groups())
    if e <= 2 or not 0 < math.hypot(nx - float(x), ny - float(y)) <= 3:
        raise ValueError('Unexpected first skirt segment')
    shutdown = ['M400', 'M104 S0', 'M140 S0', 'M107', 'G91', 'G1 Z5 F300',
                'G90', 'G1 X50 Y250 F1800', 'M84']
    if lines[-len(shutdown):] != shutdown:
        raise ValueError('Unexpected shutdown or park sequence')
    # Nominal body is absolute XYZ/E throughout. Coordinate changes, homing,
    # heaters and host macros are only valid in the reviewed start/end above.
    last_z = 0.35
    for line in lines[first:-len(shutdown)]:
        if line != 'G92 E0' and line.split()[0] not in {'G1', 'M106', 'M107'}:
            raise ValueError(f'Unexpected print-body instruction: {line}')
        if line.startswith('G1 '):
            for word in line.split()[1:]:
                if word[0] in 'XY' and not 79 <= float(word[1:]) <= 121:
                    raise ValueError('Print move leaves the 42 mm square around the cradle')
                if word[0] == 'Z':
                    z = float(word[1:])
                    if not last_z <= z <= 20.4:
                        raise ValueError('Unexpected Z change while printing the cradle')
                    last_z = z


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--slicer', default='prusa-slicer', help='PrusaSlicer 2.9.6 executable')
    parser.add_argument('--output-dir', type=Path, required=True, help='Local output directory')
    args = parser.parse_args()
    output = args.output_dir.resolve()
    output.mkdir(parents=True, exist_ok=True)
    with tempfile.TemporaryDirectory(dir=output) as workspace:
        tmp = Path(workspace)
        base = [args.slicer, '--datadir', str(tmp/'empty-settings'), '--threads', '1']
        version = subprocess.check_output([*base, '--help'], text=True).splitlines()[0]
        if not version.startswith('PrusaSlicer-2.9.6 '):
            raise ValueError(f'Use PrusaSlicer 2.9.6. Detected {version}')
        def run(*options):
            subprocess.run([*base, *map(str, options)], cwd=HERE.parent, check=True)
        expanded = tmp/'expanded.ini'
        raw = tmp/'native'/f'{STEM}.3mf'
        raw.parent.mkdir()
        project = tmp/f'{STEM}.3mf'
        gcode = tmp/f'{STEM}.gcode'
        control = tmp/'explicit-profile.gcode'
        run('--load', PROFILE, '--save', expanded)
        run('--load', PROFILE, '--center', '100,100', '--export-3mf', '--output', raw, 'zwave-tray.stl')
        embed_settings(raw, expanded, project)
        run('--dont-arrange', '--export-gcode', '--output', gcode, project)
        run('--load', PROFILE, '--center', '100,100', '--export-gcode', '--output', control, 'zwave-tray.stl')
        lines = commands(gcode)
        if lines != commands(control):
            raise ValueError('Standalone project differs from the original STL and explicit print profile')
        validate_start(lines)
        for path in (project, gcode):
            os.replace(path, output/path.name)


if __name__ == '__main__':
    main()
